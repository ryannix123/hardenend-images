#!/usr/bin/env python3
"""Rebuild deploy/acme-insurance.yaml, the one-file deploy, from deploy/db and deploy/base.

Run from the repository root after changing those manifests:

    python3 scripts/build-template.py

Needs PyYAML (pip install --user pyyaml).
"""
from pathlib import Path
import json

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "acme-insurance.yaml"
REPO = "quay.io/ryan_nix/acme-insurance"
SOURCES = [
    "deploy/db/postgres.yaml",
    "deploy/base/quote-api.yaml",
    "deploy/base/web.yaml",
    "deploy/db/networkpolicy.yaml",
    "deploy/base/networkpolicy.yaml",
]

HEADER = """# =============================================================================
# Acme Insurance demo: everything in one file
#
# Deploys the web front end, the pricing service and PostgreSQL into whatever
# project you are logged in to. Nothing to edit, no project name to pass, and
# the database password is generated for you.
#
#   Deploy (UBI build):
#     oc process -f deploy/acme-insurance.yaml | oc apply -f -
#
#   Deploy the Hardened Images build from the start:
#     oc process -f deploy/acme-insurance.yaml -p BASE=hardened | oc apply -f -
#
#   Switch builds while people watch, and pull new builds on cue:
#     scripts/demo.sh switch hardened     (or: switch ubi)
#     scripts/demo.sh pull
#   The cluster also checks Quay for new builds on its own, about every 15
#   minutes, and rolls each one out.
#
#   Open it:
#     oc get route acme-insurance -o jsonpath='https://{.spec.host}{"\\n"}'
#
#   Remove it:
#     oc delete all,secret,pvc,networkpolicy -l app.kubernetes.io/part-of=acme-insurance
#
# Run the deploy command once. Each run generates a new database password; if
# you do run it again, restart the two pods that use it:
#     oc rollout restart deployment/acme-db deployment/quote-api
#
# GENERATED from deploy/db and deploy/base by scripts/build-template.py.
# Edit those files, then re-run the script; do not edit this file by hand.
# =============================================================================
"""


class Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def main():
    objects = []
    for src in SOURCES:
        with open(ROOT / src) as f:
            objects += [d for d in yaml.safe_load_all(f) if d]

    services = []
    for obj in objects:
        # The Template deploys into the current project, so nothing may pin a namespace.
        obj["metadata"].pop("namespace", None)
        if obj["kind"] != "Deployment":
            continue
        for c in obj["spec"]["template"]["spec"]["containers"]:
            if c["image"].startswith(REPO + ":"):
                service = c["image"].split(":")[1].replace("-ubi-latest", "")
                services.append(service)
                c["image"] = "${IMAGE_REPO}:" + service + "-${BASE}-latest"
                # Roll out automatically whenever the ImageStream sees a new build.
                trigger = [{
                    "from": {"kind": "ImageStreamTag",
                             "name": "acme-insurance:" + service + "-${BASE}-latest"},
                    "fieldPath": 'spec.template.spec.containers[?(@.name=="%s")].image' % c["name"],
                }]
                obj["metadata"].setdefault("annotations", {})[
                    "image.openshift.io/triggers"] = json.dumps(trigger, separators=(",", ":"))

    # One ImageStream that watches every tag the demo uses in Quay. It re-checks
    # Quay on a schedule, and the Deployment triggers above roll out each new
    # digest it finds. Nothing is copied into the cluster registry: pods pull
    # from Quay by digest ("Source" reference policy).
    image_stream = {
        "apiVersion": "image.openshift.io/v1",
        "kind": "ImageStream",
        "metadata": {"name": "acme-insurance"},
        "spec": {
            "lookupPolicy": {"local": False},
            "tags": [
                {
                    "name": f"{svc}-{base}-latest",
                    "from": {"kind": "DockerImage", "name": "${IMAGE_REPO}:" + f"{svc}-{base}-latest"},
                    "importPolicy": {"scheduled": True},
                    "referencePolicy": {"type": "Source"},
                }
                for svc in services for base in ("ubi", "hardened")
            ],
        },
    }

    secret = {
        "apiVersion": "v1",
        "kind": "Secret",
        "metadata": {"name": "acme-db"},
        "type": "Opaque",
        "stringData": {
            "POSTGRESQL_USER": "acme",
            "POSTGRESQL_PASSWORD": "${DB_PASSWORD}",
            "POSTGRESQL_DATABASE": "acme",
        },
    }

    template = {
        "apiVersion": "template.openshift.io/v1",
        "kind": "Template",
        "metadata": {
            "name": "acme-insurance",
            "annotations": {
                "openshift.io/display-name": "Acme Insurance demo",
                "description": "Car insurance demo: Node.js 24 front end, .NET 10 pricing service "
                               "and PostgreSQL 16. Deploys into the current project.",
                "tags": "demo,dotnet,nodejs,postgresql",
            },
        },
        "labels": {"app.kubernetes.io/part-of": "acme-insurance"},
        "parameters": [
            {"name": "BASE", "displayName": "Base image",
             "description": '"ubi" for the UBI build, "hardened" for the Red Hat Hardened Images build.',
             "value": "ubi", "required": True},
            {"name": "IMAGE_REPO", "displayName": "Image repository",
             "description": "Repository that holds all four images.",
             "value": REPO, "required": True},
            {"name": "DB_PASSWORD", "displayName": "Database password",
             "description": "Generated automatically. Never stored in Git.",
             "generate": "expression", "from": "[a-zA-Z0-9]{24}", "required": True},
        ],
        "objects": [secret, image_stream] + objects,
    }

    body = yaml.dump(template, Dumper=Dumper, sort_keys=False, default_flow_style=False, width=120)
    OUT.write_text(HEADER + body)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(template['objects'])} objects")


if __name__ == "__main__":
    main()
